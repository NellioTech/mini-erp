const { api, save, verify, close, randomUUID } = require('./lib');

let fail = 0;
async function ok(name, fn) {
  try { const r = await fn(); console.log('✓', name, r?.主鍵 || ''); return r; }
  catch (e) { fail++; console.log('✗', name, '→', e.message); }
}
async function reject(name, fn) {
  try { await fn(); fail++; console.log('✗', name, '→ 應被拒絕卻成功'); }
  catch (e) { console.log('✓', name, '→ 已拒絕：', e.message); }
}

